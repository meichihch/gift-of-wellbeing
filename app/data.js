// 依 need key 取得 need 物件
window.giftNeedByKey = function (key) {
  return (window.GIFT_DATA.needs || []).find((x) => x.key === key) || null;
};

// 從某類隨機抽一句（回傳 {word, index}）
window.giftRandomWord = function (need) {
  const ws = (need && need.words) || [];
  if (!ws.length) return { word: "", index: 0 };
  const index = Math.floor(Math.random() * ws.length);
  return { word: ws[index], index };
};

// 依 key + index 取得指定那一句（給分享連結用）
window.giftWordAt = function (key, index) {
  const n = window.giftNeedByKey(key);
  if (!n || !n.words || !n.words.length) return "";
  const i = Math.max(0, Math.min(n.words.length - 1, Number(index) || 0));
  return n.words[i];
};
